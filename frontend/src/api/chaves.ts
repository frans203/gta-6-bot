/** Chaves do React Query num lugar só (usadas nos hooks e na invalidação por eventos). */
export const chaves = {
  sistema: ['sistema'] as const,
  contas: ['contas'] as const,
  videos: (conta: string) => ['videos', conta] as const,
  videosTodos: ['videos'] as const,
  plano: (conta: string, filtros: object) => ['plano', conta, filtros] as const,
  planoTodos: ['plano'] as const,
  posts: (filtros: object) => ['posts', filtros] as const,
  postsTodos: ['posts'] as const,
  horarios: ['horarios'] as const,
  tarefasWindows: ['tarefas-windows'] as const,
  jobs: (filtros: object = {}) => ['jobs', filtros] as const,
  jobsTodos: ['jobs'] as const,
  job: (id: number) => ['job', id] as const,
  logs: ['logs'] as const,
  prints: ['prints'] as const,
  plugins: ['plugins'] as const,
  modelos: ['modelos'] as const,
  fundos: ['fundos'] as const,
  streamers: ['streamers'] as const,
  streamer: (id: number) => ['streamer', id] as const,
  fontes: (streamerId?: number) => ['fontes', streamerId ?? 'todas'] as const,
  fontesTodas: ['fontes'] as const,
  cortes: (filtros: object) => ['cortes', filtros] as const,
  cortesTodos: ['cortes'] as const,
  editor: (corteId: number) => ['editor', corteId] as const,
}
